"""Работодатель-физлицо: имя человека не должно попасть в интерфейс."""

import pytest

from enrichment.employer import is_person


@pytest.mark.parametrize(
    "name",
    [
        "ИП Иванов",
        "ЧП Сидоров А.А.",
        "Сейткали Нурлан Ерланулы",
        "Петров С. И.",
        "Студия Пример (Смирнов С.С.)",
        "Ли И. В.",
        "СИДОРОВ А.С.",
        "Кузьмин",
        "Петренко",
        "ИВАНОВ",
        "КУЗЬМИН М К",
        "ИВАНОВА МАРИЯ ПЕТРОВНА",
    ],
)
def test_физлицо(name):
    assert is_person(name)


@pytest.mark.parametrize(
    "name",
    [
        "Kaspi.kz",
        "Ipotekabank OTP Group",
        "Завод им.С.М.Кирова, АО",
        "Ташкентский трубный завод имени В.Л. Гальперина",
        "СП ООО MILK HOUSE Т.М. Musaffo",
        "КАЗАХСТАНСКИЙ МЕЖДУНАРОДНЫЙ КОЛЛЕДЖ",
        "ГРИН-АПИ",
        "Нестле Фуд Казахстан",
        "Банк ЦентрКредит",
        "Ростелеком",
        "",
        None,
    ],
)
def test_компания(name):
    assert not is_person(name)
