"""Работодатель — физическое лицо? Тогда его название — имя человека.

Такие названия не показываются (docs/legal-pii-decision.md): ИП, частные
предприятия и просто люди, разместившие вакансию.

Принцип осторожный. Спрятать название компании под «частный работодатель» —
мелкая потеря. Показать имя человека — вопрос персональных данных. Поэтому
сомнительные случаи считаются физлицами.

Почему не одно правило «есть отчество»: первая версия пропускала
«Кузьмин», «Петров С. И.», «ИВАНОВ» — фамилию без отчества,
с инициалами, капсом.
"""

from __future__ import annotations

import re

# Формы, которые означают физлицо
_PERSON_FORM = re.compile(r"^(ИП|ЖК|ЧП|Индивидуальный предприниматель)\b", re.I)
# Отчество: русское, казахское, узбекское, кыргызское
_PATRONYMIC = re.compile(r"(вич|вна|улы|ұлы|уулу|кызы|қызы|оглы|угли)\b", re.I)
# Формы юрлиц: при них инициалы — часть названия («Завод им. С.М. Кирова, АО»)
_COMPANY_FORM = re.compile(
    r"\b(ТОО|АО|ООО|ОАО|ЗАО|ПАО|ОсОО|СП|ГУП|ГОУ|РГП|ГКП|LLP|LLC|Ltd|Inc|JSC|GmbH|PLC)\b|\bим\.|\bимени\b",
    re.I,
)
_INITIALS = re.compile(r"(?<![А-ЯЁA-Z])[А-ЯЁ]\.\s?[А-ЯЁ]\.?(?![а-яё])")
_SUFFIX = r"(ов|ев|ёв|ин|ын|ова|ева|ёва|ина|ына|енко|ук|юк|ко)"
# Одно слово с фамильным окончанием: «Кузьмин», «Петренко»
_SINGLE_SURNAME = re.compile(rf"^[А-ЯЁ][а-яё]+{_SUFFIX}$")
# Фамилия капсом, возможно с именем и инициалами: «ИВАНОВ», «КУЗЬМИН М К»
_CAPS_SURNAME = re.compile(rf"^[А-ЯЁ]+{_SUFFIX.upper()}( [А-ЯЁ]+){{0,2}}( [А-ЯЁ]\.?){{0,2}}$")


def is_person(name: str | None) -> bool:
    """Похоже ли название работодателя на имя человека."""
    if not name:
        return False
    t = " ".join(name.split())
    if _PERSON_FORM.search(t) or _PATRONYMIC.search(t):
        return True
    if _COMPANY_FORM.search(t):
        return False
    return bool(_INITIALS.search(t) or _SINGLE_SURNAME.match(t) or _CAPS_SURNAME.match(t))
